inline bool baseSurfaceReferenceCases(std::string& error)
{
    using namespace basesurfacereflection;
    const Direction n {0, 0, 1};
    const auto f0 = dielectricF0(1.5);
    const auto front = direct({}, 0, 0.5, f0, 0, n, n, n);
    const auto oblique = direct({}, 0, 0.5, f0, 0, n, n, {std::sqrt(0.75), 0, 0.5});
    // Authored binary64 results from the independent D * G * F / (4 NL NV)
    // calculation, not shader output or values generated by this reference.
    if (std::abs(front[0] - 0.05092958178940652) > 1e-12
        || std::abs(oblique[0] - 0.004325172741497052) > 1e-10
        || dielectricF0(3, false) != 0.04
        || direct({}, 0, 0.5, f0, 0, n, {}, n) != Color {}
        || direct({}, 0, 0.5, f0, 0, n, n, {0, 0, -1}) != Color {})
    { error = "Direct GGX reference differs from independent authored views/direction policy"; return false; }
    double reflected = 0, whiteEnergy = 0;
    constexpr int slices = 4096;
    for (int i = 0; i < slices; ++i)
    {
        const auto cosine = (i + 0.5) / slices;
        const Direction light {std::sqrt(1 - cosine * cosine), 0, cosine};
        reflected += direct({}, 0, 0.5, f0, 0, n, light, n)[0] * 2 * kPi / slices;
        whiteEnergy += direct({1, 1, 1}, 0, 0.5, f0, 0, n, light, n)[0] * 2 * kPi / slices;
    }
    if (std::abs(reflected - 0.03665877) > 2e-6 || !(whiteEnergy <= 1.000001))
    { error = "Direct GGX hemisphere violates independent single-scatter/energy oracle"; return false; }
    for (const auto roughness : {0.0, 1.0})
        for (const auto view : {Direction {1, 0, 1e-8}, n})
            for (auto value : direct({1, 1, 1}, 0, roughness, f0, 0, n, n, view))
                if (!std::isfinite(value) || value < 0)
                { error = "Direct GGX roughness/grazing limit is not finite"; return false; }
    return true;
}

inline bool baseSurfaceReflectionCases(arbitgpu::NativeFixtureSceneBackend& backend,
                                      std::string& error)
{
    if (!baseSurfaceReferenceCases(error)) return false;
    using namespace HarmonicMIDI::grid;
    struct Case { float angle; float ior; float roughness; float metallic; float base;
                  SceneLightKind kind; float intensity; bool explicitMaterial; double expected; bool behind = false; float range = 0; bool secondLight = false; };
    // Independent authored expectations: front D=16/pi, F=.04; at 60 degrees
    // NH=cos(30), Smith G1(V)=1/(.5+sqrt(.296875)), F=.0400414365.
    const Case cases[] {
        {0, 1.5f, .5f, 0, 0, SceneLightKind::Directional, 1, true, .05092958178940652},
        {60, 1.5f, .5f, 0, 0, SceneLightKind::Directional, 1, true, .004325172741497052},
        {80, 1.5f, .5f, 0, 0, SceneLightKind::Directional, 1, true, 0.004209571300242781},
        {0, 1.5f, 0, 0, 0, SceneLightKind::Directional, 1, true, 509.2958178964391},
        {0, 1.5f, .5f, 0, 0, SceneLightKind::Directional, 1, true, 0, true},
        {0, 1, .5f, 0, 0, SceneLightKind::Directional, 1, true, 0},
        {0, 2, .5f, 0, 0, SceneLightKind::Directional, 1, true, .14147106052612918},
        {0, 1.5f, 1, 0, 0, SceneLightKind::Directional, 1, true, .003183098861837907},
        {0, 1.5f, .5f, 1, 1, SceneLightKind::Directional, 1, true, 1.2732395447351628},
        {0, 1.5f, .5f, 0, 1, SceneLightKind::Directional, 1, true, .3565070725258456},
        {0, 1.5f, .5f, 0, 0, SceneLightKind::Directional, 0, true, 0},
        {0, 1.5f, .5f, 0, 0, SceneLightKind::Point, 1, true, .01273239544735163},
        {0, 1.5f, .5f, 0, 0, SceneLightKind::Point, 1, true, .003183098861837907, false, 4},
        {0, 1.5f, .5f, 0, 0, SceneLightKind::Spot, 1, true, .01273239544735163},
        {0, 1.5f, .5f, 0, 0, SceneLightKind::Spot, 1, true, 0, true},
        {0, 1.5f, .5f, 0, 0, SceneLightKind::Directional, 1, true, .06366197723675815, false, 0, true},
        {0, 1.5f, .5f, 0, 0, SceneLightKind::Directional, 1, false, .05092958178940652}
    };
    for (const auto& test : cases)
    {
        auto value = fixture3d::makeScene();
        value.vertexCount = 4; value.indexCount = 6;
        value.objects[0].vertexCount = 4; value.objects[0].indexCount = 6;
        value.objects[0].transform = {};
        value.ambientColor = {}; value.lightCount = 1;
        value.materials[0].baseColor = {test.base, test.base, test.base};
        value.materials[0].baseColorTexture = {};
        value.materials[0].metallic = test.metallic; value.materials[0].roughness = test.roughness;
        value.materials[0].emissive = {};
        value.lights[0].kind = test.kind; value.lights[0].transform = {};
        value.lights[0].transform.translation = {0, 0, 3};
        value.lights[0].color = {1, 1, 1}; value.lights[0].intensity = test.intensity;
        value.lights[0].range = test.range;
        if (test.behind) value.lights[0].transform.rotation = {0, 1, 0, 0};
        if (test.secondLight)
        {
            value.lightCount = 2; value.lights[1] = value.lights[0];
            value.lights[1].id = SceneLightId {302};
            value.lights[1].kind = SceneLightKind::Point;
        }
        const auto radians = test.angle * basesurfacereflection::kPi / 180;
        // Both views re-aim at the identical front-plane target (0,0,1).
        value.cameras[0].transform.translation = {
            static_cast<float>(4 * std::sin(radians)), 0, static_cast<float>(1 + 4 * std::cos(radians))};
        value.cameras[0].transform.rotation = {0, static_cast<float>(std::sin(radians / 2)),
            0, static_cast<float>(std::cos(radians / 2))};
        const auto scene = std::make_shared<const Visual3DScene>(std::move(value));
        std::shared_ptr<arbitgpu::NativeFixtureSurfaceMaterialProgram> material;
        if (test.explicitMaterial)
        {
            material = std::make_shared<arbitgpu::NativeFixtureSurfaceMaterialProgram>();
            material->backend = backend.info().backend == "metal"
                ? arbitgpu::NativeFixtureMaterialBackend::Metal : arbitgpu::NativeFixtureMaterialBackend::OpenGl;
            material->object = fixture3d::kCubeObjectId;
            material->bindingDigest = "direct-base-ggx-fixture-binding";
            material->programIdentity = "direct-base-ggx-fixture-program";
            material->baseColorSource = arbitgpu::NativeFixtureSurfaceMaterialProgram::BaseColorSource::ConstantLinear;
            material->parameters.baseColorMetallic = {test.base, test.base, test.base, test.metallic};
            material->parameters.emissionRoughness = {0, 0, 0, test.roughness};
            material->parameters.normalOpacity = {0, 0, 1, 1};
            material->parameters.transmissionIorClearcoat = {0, test.ior, 0, 0};
            material->parameters.identifiers = {fixture3d::kCubeMaterialId.value, 0, 0, 0};
        }
        const auto prepared = backend.prepare(scene, material);
        if (!prepared.prepared) { error = prepared.error; return false; }
        arbitgpu::NativeFixtureSceneRuntimeInputs inputs; inputs.linearColor = true;
        const auto frame = backend.render(scene, prepared.resources, 65, 65, inputs);
        arbitgpu::NativeRawPassPixels pixels;
        if (!frame.rendered || !frame.frame
            || !frame.frame->readRawPass(renderpassoutput::Output::Color, pixels, error)
            || pixels.format != arbitgpu::NativeTexturePixelFormat::Rgba16Float
            || pixels.bytes.size() != 65 * 65 * 8)
        { error = "Missing direct GGX native float center: " + frame.error + error; return false; }
        const auto center = (32 * 65 + 32) * 8;
        // Window center (32.5,32.5) has NDC (0,0). The front plane is z=1;
        // each authored camera aims at (0,0,1), four units away. Verify that
        // the color sample actually has that plane's normal and depth.
        arbitgpu::NativeRawPassPixels normals, depths;
        if (!frame.frame->readRawPass(renderpassoutput::Output::Normal, normals, error)
            || !frame.frame->readRawPass(renderpassoutput::Output::Depth, depths, error)
            || normals.format != arbitgpu::NativeTexturePixelFormat::Rgba16Float
            || depths.format != arbitgpu::NativeTexturePixelFormat::R32Float
            || normals.bytes.size() != pixels.bytes.size() || depths.bytes.size() != 65 * 65 * 4)
        { error = "Missing direct GGX center plane normal/depth: " + error; return false; }
        const std::uint16_t expectedNormal[] {0, 0, 0x3c00, 0x3c00};
        for (int channel = 0; channel < 4; ++channel)
        {
            std::uint16_t half; std::memcpy(&half, normals.bytes.data() + center + channel * 2, 2);
            if (hdrimage::halfToFloat(half) != hdrimage::halfToFloat(expectedNormal[channel]))
            { error = "Direct GGX center does not sample front-plane normal (0,0,1)"; return false; }
        }
        float depth; std::memcpy(&depth, depths.bytes.data() + (32 * 65 + 32) * 4, 4);
        const auto& camera = scene->cameras[0];
        const auto expectedDepth = (4.0 - camera.nearPlane) / (camera.farPlane - camera.nearPlane);
        if (!std::isfinite(depth) || std::abs(depth - expectedDepth) > 1e-7)
        { error = "Direct GGX center does not sample the authored target (0,0,1), angle "
                  + std::to_string(test.angle) + ", depth " + std::to_string(depth); return false; }
        for (int channel = 0; channel < 4; ++channel)
        {
            std::uint16_t half; std::memcpy(&half, pixels.bytes.data() + center + channel * 2, 2);
            const auto actual = hdrimage::halfToFloat(half);
            const auto expected = channel == 3 ? 1.0 : test.expected;
            // Bracket the binary64 oracle by shader float roundoff, then by
            // adjacent binary16 storage values. Zero and opaque alpha are exact.
            double low = expected, high = expected;
            if (channel < 3 && expected > 0)
            {
                const auto roundoff = expected * 64 * std::numeric_limits<float>::epsilon();
                low -= roundoff; high += roundoff;
                if (test.roughness == 0)
                {
                    // At NL=NV=NH=VH=1, D*G*F/4 is F0/(4*pi*a2).
                    // Shader reassociation to 1+(a2-1)*NH^2 rounds a2 through
                    // subtraction near one. Explicit binary32 steps independently
                    // predict 507.9154, rather than binary64 509.2958. This is
                    // confined to the minimum-alpha case, not a relative allowance.
                    const auto binary32 = [](double value) {
                        volatile float rounded = static_cast<float>(value);
                        return static_cast<double>(rounded);
                    };
                    const auto alpha = binary32(0.0025);
                    const auto a2 = binary32(alpha * alpha);
                    const auto denominator = binary32(1.0 + binary32(a2 - 1.0));
                    const auto distribution = binary32(a2 / binary32(binary32(basesurfacereflection::kPi)
                        * binary32(denominator * denominator)));
                    const auto ratio = binary32((test.ior - 1.0) / (test.ior + 1.0));
                    const auto reassociated = binary32(binary32(distribution * .25)
                        * binary32(ratio * ratio));
                    low = std::min(low, reassociated - roundoff);
                    high = std::max(high, reassociated + roundoff);
                }
                int exponent = 0; std::frexp(expected, &exponent);
                const auto step = std::ldexp(1.0, std::max(exponent - 11, -24));
                low = std::floor(low / step) * step;
                high = std::ceil(high / step) * step;
            }
            if (!std::isfinite(actual) || actual < low || actual > high)
            { error = "Direct GGX native view/light center differs: expected " + std::to_string(expected)
                    + ", storage bounds [" + std::to_string(low) + ", " + std::to_string(high)
                    + "], actual " + std::to_string(actual) + ", angle " + std::to_string(test.angle); return false; }
        }
    }
    return true;
}
